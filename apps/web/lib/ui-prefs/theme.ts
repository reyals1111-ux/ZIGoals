import {UI_PREFS_KEY} from '../ab-design-keys';
import {uiPrefsSchema, type UiPrefs} from './schema';
import {THEME_SHEETS} from './theme-sheets';

/**
 * Session AD (Part 3, ADR-026 F4/F5): the theme is a device display choice, like Motion Off. It lives in this device's own
 * `zigoals:ui-prefs:v1` record (plain localStorage, the record a device without an account or the Showcase uses), so it is
 * the same in every mode and the page can read it before it paints (app/theme-boot.ts). Never synced. Nebula is the
 * default and loads nothing; Light and Dark add their own stylesheet (public/themes/, generated by
 * scripts/themes/build-themes.mjs) and `data-theme` on <html>.
 */
/* Session AD: the theme helpers live here, with the lazily loaded theme bar, not in the schema every page loads. */
/** Session AD: the three themes. Nebula is today's look and the default for everyone; Light and Dark are previews. */
export const THEMES = ['nebula', 'light', 'dark'] as const;
export type Theme = typeof THEMES[number];
/** The theme a record asks for; anything unknown (a later build's theme, a typo) reads as nebula. */
export const themeOf = (prefs: Pick<UiPrefs, 'theme'> | null | undefined): Theme => (THEMES as readonly string[]).includes(prefs?.theme ?? '') ? prefs!.theme as Theme : 'nebula';
export const THEME_EVENT = 'zigoals-theme';
const LINK_ID = 'zigoals-theme-sheet';

export function readTheme(storage: Pick<Storage, 'getItem'> | null = safeLocal()): Theme {
  try { const raw = storage?.getItem(UI_PREFS_KEY); if (!raw) return 'nebula'; const parsed = uiPrefsSchema.safeParse(JSON.parse(raw)); return parsed.success ? themeOf(parsed.data) : 'nebula'; } catch { return 'nebula'; }
}
/** Stores the choice, keeping every other field of the record as it is (unreadable bytes are replaced only by a fresh record). */
export function writeTheme(theme: Theme, storage: Pick<Storage, 'getItem' | 'setItem'> | null = safeLocal()): void {
  if (!storage) throw Error('This browser could not save the theme.');
  let record: Record<string, unknown> = {version: 1};
  try { const raw = storage.getItem(UI_PREFS_KEY); if (raw) { const parsed = uiPrefsSchema.safeParse(JSON.parse(raw)); if (parsed.success) record = parsed.data; } } catch { /* a fresh record */ }
  const next: Record<string, unknown> = {...record};
  if (theme === 'nebula') delete next.theme; else next.theme = theme;
  storage.setItem(UI_PREFS_KEY, JSON.stringify(next));
}
/** Puts a theme on the page now: the attribute on <html> and the theme's own stylesheet (none for Nebula). */
export function applyTheme(theme: Theme, doc: Document = document): void {
  const root = doc.documentElement;
  if (theme === 'nebula') delete root.dataset.theme; else root.dataset.theme = theme;
  const href = theme === 'nebula' ? null : THEME_SHEETS[theme];
  let link = doc.getElementById(LINK_ID) as HTMLLinkElement | null;
  if (!href) { link?.remove(); return; }
  if (link?.getAttribute('href') === href) return;
  if (!link) { link = doc.createElement('link'); link.id = LINK_ID; link.rel = 'stylesheet'; doc.head.appendChild(link); }
  link.href = href;
}
/** Choose: store, apply, and tell the other theme bars on the page (and other tabs, through the storage event). */
export function chooseTheme(theme: Theme): void {
  writeTheme(theme);
  applyTheme(theme);
  window.dispatchEvent(new Event(THEME_EVENT));
}
function safeLocal(): Storage | null { try { return typeof window === 'undefined' ? null : window.localStorage; } catch { return null; } }
